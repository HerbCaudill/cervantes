/** Build the PDF.js surface used by crop inference without loading a document. */
function createPage(
  /** One-based source PDF page number */
  pageNumber: number,
): PDFPageProxy {
  return {
    pageNumber,
    view: [0, 0, 595.276, 841.89],
    getOperatorList: async () => ({ fnArray: [], argsArray: [] }),
  } as unknown as PDFPageProxy
}
